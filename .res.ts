import postgres from "postgres";
const url = `postgres://${process.env.PGUSER}:${encodeURIComponent(process.env.PGPASSWORD!)}@${process.env.RAILWAY_TCP_PROXY_DOMAIN}:${process.env.RAILWAY_TCP_PROXY_PORT}/${process.env.PGDATABASE}`;
const sql = postgres(url, { ssl: { rejectUnauthorized: false }, max: 2 });
const W = ["0x3e6f8ca8fbae3ff7e3d1f68a50e3119ddb716d29", "0xc8b7aefc4a85bbec9c2e7db9850c56eddd2800b2"];
const cols = await sql`select column_name from information_schema.columns where table_name='quest_results' order by ordinal_position`;
console.log("quest_results cols:", cols.map((c: any) => c.column_name).join(", "));
const rows = await sql`select * from quest_results where day = 20774 and lower(address) = any(${W}) order by address, quest_id`;
console.log(`\nrows for day 20774: ${rows.length}`);
for (const r of rows as any[]) console.log(`  ${r.address.slice(0,10)} ${String(r.quest_id).padEnd(16)} ${JSON.stringify(Object.fromEntries(Object.entries(r).filter(([k]) => !["address","day","quest_id"].includes(k))))}`);
console.log("\n=== all race.* results today, any wallet ===");
const all = await sql`select quest_id, count(*) as n from quest_results where day = 20774 and quest_id like 'race.%' group by quest_id`;
console.log(all.length ? all.map((x: any) => `${x.quest_id}=${x.n}`).join(", ") : "  NONE");
console.log("\n=== all results today by quest (top 12) ===");
const byq = await sql`select quest_id, count(*) as n from quest_results where day = 20774 group by quest_id order by n desc limit 12`;
for (const x of byq as any[]) console.log(`  ${String(x.quest_id).padEnd(18)} ${x.n}`);
await sql.end();
